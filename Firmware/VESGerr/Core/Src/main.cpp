void setNative6PWM(float dc_a, float dc_b, float dc_c) {
    // VESC 4.12 board layout maps to TIM1 channels as: Phase A->CH3, Phase B->CH2, Phase C->CH1
    TIM1->CCR3 = (uint32_t)(dc_a * 4199.0f);
    TIM1->CCR2 = (uint32_t)(dc_b * 4199.0f);
    TIM1->CCR1 = (uint32_t)(dc_c * 4199.0f);
}
