/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
	float electrical_angle = 0.0f;
	float target_velocity = 3.0f; // Velocity target in rad/s (slow and safe for bench testing)
	DQVoltage driver_output;     // Structure to hold our calculated Space Vector voltages
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  /* USER CODE BEGIN 2 */
  // Turn on the DRV8302 Gate Driver enable line
  HAL_GPIO_WritePin(GPIOC, GPIO_PIN_10, GPIO_PIN_SET);
  HAL_Delay(50);

  // Start all 3 high-side and low-side complementary PWM channels on TIM1
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
  HAL_TIMEx_PWMN_Start(&htim1, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_2);
  HAL_TIMEx_PWMN_Start(&htim1, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_3);
  HAL_TIMEx_PWMN_Start(&htim1, TIM_CHANNEL_3);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	// 1. Manually step the electrical positioning forward over time
	electrical_angle = _normalizeAngle(electrical_angle + target_velocity * 0.001f);

	// 2. Set an open-loop voltage envelope (1.0 Volt out of 12V is plenty for a bench test)
	float u_q = 1.0f;
	float u_d = 0.0f;

	// 3. Compute the bare-metal Space Vector Modulation profiles natively
	_inverseParkAndSVPWM(u_d, u_q, electrical_angle, &driver_output);

	// 4. Update the VESC MOSFET timers instantly via register execution
	setNative6PWM(driver_output.dc_a, driver_output.dc_b, driver_output.dc_c);

	// High-speed hardware fault clearing logic
	if (HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_12) == GPIO_PIN_RESET) {
		HAL_GPIO_WritePin(GPIOC, GPIO_PIN_10, GPIO_PIN_RESET); // Drop gate
		for(volatile int i=0; i<50; i++);                      // Settle delay
		HAL_GPIO_WritePin(GPIOC, GPIO_PIN_10, GPIO_PIN_SET);   // Reset latch
	}

	HAL_Delay(1); // Execute the positioning steps at a steady 1 kHz update rate
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

